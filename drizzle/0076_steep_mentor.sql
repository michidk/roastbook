CREATE FUNCTION journal_changed() RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE journal_owner text;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN RETURN NEW; END IF;
  IF TG_OP = 'DELETE' THEN journal_owner := OLD.owner_id; ELSE journal_owner := NEW.owner_id; END IF;
  INSERT INTO journal_sync_revisions (owner_id, value) VALUES (journal_owner, 1)
  ON CONFLICT (owner_id) DO UPDATE SET value = journal_sync_revisions.value + 1;
  IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
